package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/KoJaco/ambit/internal/core"
)

const briefUsage = "usage: ambit brief export [--node id | --all] [--out dir] [--force]\n"

// briefMarker tells a later export that it wrote the file and may replace it.
const briefMarker = "Generated by `ambit brief export`"

// cmdBrief exports node briefs (the text get_context returns) as files an agent can read
// without the MCP server, for example to hand to a subagent.
func cmdBrief(dir string, args []string, stdout, stderr io.Writer) int {
	if len(args) == 0 || args[0] != "export" {
		fmt.Fprint(stderr, briefUsage)
		return 1
	}
	var node, out string
	all, force := false, false
	for i := 1; i < len(args); i++ {
		switch {
		case args[i] == "--all":
			all = true
		case args[i] == "--force":
			force = true
		case args[i] == "--node" && i+1 < len(args):
			node = args[i+1]
			i++
		case args[i] == "--out" && i+1 < len(args):
			out = args[i+1]
			i++
		default:
			fmt.Fprint(stderr, briefUsage)
			return 1
		}
	}
	if all == (node != "") {
		fmt.Fprint(stderr, briefUsage)
		return 1
	}
	idx, err := core.Open(dir)
	if err != nil {
		fmt.Fprintf(stderr, "ambit brief export: %v\n", err)
		return 1
	}
	for _, w := range idx.Warnings() {
		fmt.Fprintln(stderr, w.String())
	}
	if out == "" {
		out = filepath.Join(dir, ".arch", "briefs")
	}
	ids := idx.BriefNodeIDs()
	if node != "" {
		ids = []core.NodeID{core.NodeID(node)}
	}
	failed := 0
	for _, id := range ids {
		text, err := idx.Brief(id)
		if err != nil {
			fmt.Fprintf(stderr, "ambit brief export: %v\n", err)
			return 1
		}
		if filepath.Base(string(id)) != string(id) || strings.ContainsAny(string(id), `/\`) {
			fmt.Fprintf(stderr, "ambit brief export: node id %q is not a safe file name\n", id)
			return 1
		}
		path := filepath.Join(out, string(id)+".md")
		if existing, rerr := os.ReadFile(path); rerr == nil && !force && !strings.Contains(string(existing), briefMarker) {
			fmt.Fprintf(stderr, "ambit brief export: %s exists and was not generated by ambit; pass --force to overwrite it\n", path)
			failed++
			continue
		}
		if err := os.MkdirAll(out, 0o755); err != nil {
			fmt.Fprintf(stderr, "ambit brief export: %v\n", err)
			return 1
		}
		body := fmt.Sprintf("<!-- %s. Do not edit; the model is the source of truth, so regenerate after changing it. -->\n\n%s", briefMarker, text)
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			fmt.Fprintf(stderr, "ambit brief export: %v\n", err)
			return 1
		}
		fmt.Fprintf(stdout, "wrote %s\n", path)
	}
	if failed > 0 {
		return 1
	}
	return 0
}
